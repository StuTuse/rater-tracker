export function flattenFeedback(node = feedbackGroups, prefix = '') {
  return Object.entries(node).flatMap(([key, value]) => Array.isArray(value)
    ? value.map((text, index) => ({ id: `${prefix}${key}.${index + 1}`, text }))
    : flattenFeedback(value, `${prefix}${key}.`));
}
