// Load with Playwright CLI run-code --filename. Requires a fresh snapshot of today's page.
async (page) => {
  const results = {};
  const settle = () => page.evaluate(() => Promise.all(document.getAnimations().map(a => a.finished.catch(() => {}))));
  const read = () => page.evaluate(async () => { const {openStore}=await import('./src/storage.js'); const {totalUnits,stats}=await import('./src/core.js'); const store=await openStore(); const s=await store.read(); store.close(); return {total:totalUnits(s),revision:s.revision,stats:stats(s)}; });
  await page.reload(); await page.evaluate(() => window.raterReady);
  await page.getByRole('button',{name:'学习 3 星',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[data-stars="3"][data-dimension="study"]').getAttribute('aria-pressed')==='true');
  const initial = await read();
  results.reopen = initial.total > 0;
  await page.evaluate(() => { window.originalPut=IDBObjectStore.prototype.put; IDBObjectStore.prototype.put=function(){throw new DOMException('模拟磁盘写入失败','QuotaExceededError');}; });
  await page.getByRole('button',{name:'学习 5 星',exact:true}).click();
  await page.waitForFunction(() => document.querySelector('#save-status').textContent==='本次未保存');
  const failed = await read();
  results.failedWriteHasNoAward = initial.total===failed.total && initial.revision===failed.revision;
  await page.evaluate(() => { IDBObjectStore.prototype.put=window.originalPut; delete window.originalPut; });
  await page.getByRole('button',{name:'学习 5 星',exact:true}).click();
  await page.waitForFunction(() => document.querySelector('#save-status').textContent==='已保存到本机');
  const increased = await read(); results.retrySaved = increased.total>initial.total;
  // Rapid corrections during the running animation must converge on the last saved value.
  await page.getByRole('button',{name:'学习 4 星',exact:true}).click();
  await page.getByRole('button',{name:'学习 3 星',exact:true}).click();
  await page.waitForFunction(() => document.querySelector('[data-stars="3"][data-dimension="study"]').getAttribute('aria-pressed')==='true');
  const final = await read(); results.rapidCorrection = final.total===initial.total;
  await page.waitForFunction(expected => Number(document.querySelector('#xp-total').textContent.replaceAll(',',''))===expected, final.total/1e6);
  results.animationFinalValue = true;
  results.storageConflict = await page.evaluate(async () => {const{openStore,ConflictError}=await import('./src/storage.js'); const store=await openStore(); const s=await store.read(); try{await store.write(s,s.revision-1);return false;}catch(e){return e instanceof ConflictError;}finally{store.close();}});
  results.backupRoundTrip = await page.evaluate(async()=>{const{openStore,parseBackup,backupText}=await import('./src/storage.js');const store=await openStore();const s=await store.read();const restored=parseBackup(backupText(s));store.close();return JSON.stringify(s)===JSON.stringify(restored);});
  await page.getByRole('button',{name:'奖励中心',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.badge-card').length===48);
  await page.waitForFunction(()=>Array.from(document.querySelectorAll('.badge-card img')).every(i=>i.complete&&i.naturalWidth>0));
  results.all48OfflineAssets = true;
  await settle(); await page.screenshot({path:'output/playwright/rewards.png',fullPage:true});
  await page.getByRole('button',{name:'历史',exact:true}).click();
  await page.getByRole('button',{name:'30 天',exact:true}).click();
  results.calendarAndTrend = await page.locator('.calendar-day').count()>0 && await page.locator('.trend-line').count()===4;
  await settle(); await page.screenshot({path:'output/playwright/history.png',fullPage:true});
  await page.getByRole('button',{name:'设置',exact:true}).click();
  await page.getByLabel('动效强度').selectOption('gentle');
  await page.waitForFunction(()=>document.documentElement.dataset.motion==='gentle');
  await page.getByLabel('动效强度').selectOption('off');
  await page.waitForFunction(()=>document.documentElement.dataset.motion==='off');
  await page.getByLabel('动效强度').selectOption('full');
  await page.waitForFunction(()=>document.documentElement.dataset.motion==='full');
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.waitForFunction(()=>document.documentElement.dataset.motion==='gentle');
  results.motionPreferences=true;
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.getByRole('button',{name:'今日',exact:true}).click();
  await page.setViewportSize({width:1440,height:960});
  await settle(); await page.screenshot({path:'output/playwright/today.png',fullPage:true});
  await page.setViewportSize({width:800,height:700});
  results.narrowDesktopNoOverflow=await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth);
  await settle(); await page.screenshot({path:'output/playwright/narrow.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  results.mobileLayoutNoOverflow=await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth);
  await settle(); await page.screenshot({path:'output/playwright/mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:960});
  console.log(JSON.stringify(results,null,2));
  if(Object.values(results).some(v=>v!==true))throw new Error('Acceptance condition failed');
  return results;
}
